DIAGRAM.set_name('Обеспечение ремонта материалами')
pool, (master, storekeeper, supply, accounting) = DIAGRAM.add_pool(ROOT_PROCESS_ID, ['Мастер участка', 'Кладовщик', 'Отдел снабжения', 'Бухгалтерия'])
p_vendor, (vendor,) = DIAGRAM.add_pool(ROOT_PROCESS_ID, ['Поставщик'])

defects = DIAGRAM.add_data_object('Ведомость дефектов', master)
need = DIAGRAM.add_user_task('Сформировать потребность в материалах', master)
stock = DIAGRAM.add_user_task('Проверить остатки на складе', storekeeper)
available = DIAGRAM.add_inclusive_gateway('Что есть на складе?', storekeeper)
issue_now = DIAGRAM.add_user_task('Выдать имеющиеся материалы', storekeeper)
offers = DIAGRAM.add_user_task('Запросить три коммерческих предложения', supply)
choose = DIAGRAM.add_user_task('Выбрать поставщика', supply)
contract = DIAGRAM.add_user_task('Заключить договор', supply)
pay = DIAGRAM.add_user_task('Оплатить счёт', accounting)
deliver = DIAGRAM.add_user_task('Поставить материалы', vendor)
receive = DIAGRAM.add_user_task('Принять материалы по накладной', storekeeper)
waybill = DIAGRAM.add_data_object('Накладная', storekeeper)
issue_later = DIAGRAM.add_user_task('Выдать закупленные материалы', storekeeper)
done = DIAGRAM.add_inclusive_gateway('', storekeeper)
sign = DIAGRAM.add_user_task('Расписаться в требовании-накладной', master)

DIAGRAM.add_link(ROOT_START_TASK_ID, need)
DIAGRAM.add_link(defects, need)
DIAGRAM.add_link(need, stock)
DIAGRAM.add_link(stock, available)
DIAGRAM.add_link(available, issue_now, name='есть часть или всё')
DIAGRAM.add_link(available, offers, name='чего-то нет')
DIAGRAM.add_link(offers, choose)
DIAGRAM.add_link(choose, contract)
DIAGRAM.add_link(contract, pay)
DIAGRAM.add_link(pay, deliver)
DIAGRAM.add_link(deliver, receive)
DIAGRAM.add_link(receive, waybill)
DIAGRAM.add_link(waybill, issue_later)
DIAGRAM.add_link(receive, issue_later)
DIAGRAM.add_link(issue_now, done)
DIAGRAM.add_link(issue_later, done)
DIAGRAM.add_link(done, sign)
DIAGRAM.add_link(sign, ROOT_END_TASK_ID)
