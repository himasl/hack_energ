DIAGRAM.set_name('Ремонт оборудования подстанции')
pool, lanes = DIAGRAM.add_pool(ROOT_PROCESS_ID, ['Диспетчер', 'Мастер участка', 'Бригада'])
dispatcher, master, crew = lanes

register = DIAGRAM.add_user_task('Зарегистрировать заявку', dispatcher)
assess = DIAGRAM.add_user_task('Оценить неисправность', master)
need_outage = DIAGRAM.add_exclusive_gateway('Требуется отключение?', master)
approve = DIAGRAM.add_user_task('Согласовать вывод в ремонт', dispatcher)
merge_outage = DIAGRAM.add_exclusive_gateway('', master)
assign = DIAGRAM.add_user_task('Назначить бригаду', master)
fork = DIAGRAM.add_parallel_gateway('', master)
materials = DIAGRAM.add_user_task('Подготовить материалы и инструмент', crew)
permit = DIAGRAM.add_user_task('Оформить наряд-допуск', master)
join = DIAGRAM.add_parallel_gateway('', crew)
repair = DIAGRAM.add_user_task('Выполнить ремонт', crew)
report = DIAGRAM.add_user_task('Доложить о завершении', crew)
close = DIAGRAM.add_script_task('Закрыть заявку', dispatcher)
journal = DIAGRAM.add_data_store('Журнал заявок', dispatcher)
permit_doc = DIAGRAM.add_data_object('Наряд-допуск', master)

DIAGRAM.add_link(ROOT_START_TASK_ID, register)
DIAGRAM.add_link(register, assess)
DIAGRAM.add_link(assess, need_outage)
DIAGRAM.add_link(need_outage, approve, name='да')
DIAGRAM.add_link(need_outage, merge_outage, name='нет')
DIAGRAM.add_link(approve, merge_outage)
DIAGRAM.add_link(merge_outage, assign)
DIAGRAM.add_link(assign, fork)
DIAGRAM.add_link(fork, materials)
DIAGRAM.add_link(fork, permit)
DIAGRAM.add_link(materials, join)
DIAGRAM.add_link(permit, join)
DIAGRAM.add_link(join, repair)
DIAGRAM.add_link(repair, report)
DIAGRAM.add_link(report, close)
DIAGRAM.add_link(close, ROOT_END_TASK_ID)
DIAGRAM.add_link(register, journal)
DIAGRAM.add_link(permit, permit_doc)
DIAGRAM.add_link(permit_doc, repair)
